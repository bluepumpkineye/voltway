"""Writes blender/scripts/su7_lampdata.py: the SU7 Ultra's headlamp, read off the maker's head-on photograph.

    blender -b --factory-startup --python gen_su7_lampdata.py

Source: reference/xiaomi-su7-ultra/lights/cat53/big_023.jpg, 1600 x 1200, the yellow car square-on from the front, through
ref_match's "front" camera. The photograph's LEFT half is the car's RIGHT; the left lamp is read here (u 403..556) and the
build mirrors the rays onto the half sheet (y >= 0).

Traced (the yellow paint is saturated, the lamp is not: R - B < 0.22, closed r=3, the loop that holds the lamp's centre,
Gaussian-smoothed 1.6 px, resampled every 4 px): the almond OUTLINE.
Read by hand from a 9x gridded crop (the photograph is lit with the DRL on, so the bar is plain to see): the DRL bar's two
edges, the silver reflector's polygon (the grey upper-right half, under the bezel), the three projector modules' centres.
"""
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "a06t_lamp_trace"))
import lampseg as LS                                                         # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
PHOTO = os.path.join(ROOT, "blender", "reference", "xiaomi-su7-ultra", "lights", "cat53", "big_023.jpg")
OUT = os.path.join(HERE, "..", "..", "su7_lampdata.py")
BOX = (385, 595, 580, 745)

L, rgb = LS.load_gray(PHOTO, BOX)
mask = LS.closing((rgb[..., 0] - rgb[..., 2]) < 0.22, 3)
loops = LS.boundary_loops(mask)
cu, cv = 490 - BOX[0], 670 - BOX[1]
best = None
for lp in loops:
    if len(lp) > 60 and LS.inside(lp, (cu, cv)) and (best is None or abs(LS.area(lp)) > abs(LS.area(best))):
        best = lp
sm = LS.smooth(best, 1.6, 1.0)
out = [(round(float(p[0] + BOX[0]), 1), round(float(p[1] + BOX[1]), 1)) for p in LS.resample(sm, 4.0)]

DRL_UP = [(413, 656), (426, 660), (439, 664), (473, 674.5), (506, 689.5), (539, 701.5), (549, 706)]
DRL_LO = [(413, 667), (426, 671), (439, 676.5), (473, 687.5), (506, 703.5), (539, 713), (549, 711)]
SILVER = [(433, 626), (457, 634), (490, 651), (522, 670), (542, 688), (551, 700), (548, 705), (539, 702), (506, 690),
          (473, 675), (450, 664)]
MODULES = [(451, 648, 7.5), (437, 687, 6.5), (460, 697, 6.0)]            # (u, v, radius in px)

with open(OUT, "w") as f:
    f.write('"""The SU7 Ultra\'s left headlamp in the pixels of big_023.jpg (1600 x 1200), see porting/su7_lamp_trace.\n'
            'Generated by gen_su7_lampdata.py: do not edit."""\n')
    f.write("SIZE = (1600, 1200)\n")
    for nm, pts in (("LAMP_OUT", out), ("DRL_UP", DRL_UP), ("DRL_LO", DRL_LO), ("SILVER", SILVER), ("MODULES", MODULES)):
        f.write("%s = [\n" % nm)
        for i in range(0, len(pts), 4):
            f.write("    " + ", ".join(repr(tuple(p)) for p in pts[i:i + 4]) + ",\n")
        f.write("]\n")
print("wrote", OUT, len(out), "outline points")
