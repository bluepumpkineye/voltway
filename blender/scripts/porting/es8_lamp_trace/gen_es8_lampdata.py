"""Writes blender/scripts/es8_lampdata.py: the Nio ES8's headlamp read off the official front photograph ext_front.jpg.

Run in Blender:   blender -b --factory-startup --python gen_es8_lampdata.py
(needs ../a06t_lamp_trace/lampseg.py for the contour helpers; the reference photographs are local only).

The DRL's lens, bars and segments are traced (luminance threshold, pixel-exact boundary chains, Gaussian-smoothed);
the pod, its two lens units, the chrome sill and the vent are hand readings of 7x crops of the same photograph
(a low-contrast dark glass: no threshold finds its edge), good to about one pixel = 2 mm.
All coordinates are pixels of ext_front.jpg (2560 x 1280); the LEFT half of the picture (the car's right) is read
and mirrored onto the model's y >= 0 half sheet by es8_front.
"""
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "a06t_lamp_trace"))
import lampseg as S                                                               # noqa: E402

ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
REF = os.path.join(ROOT, "reference", "nio-es8", "official", "ext_front.jpg")
OUT = os.path.join(ROOT, "scripts", "es8_lampdata.py")
STEP = float(os.environ.get("STEP", 1.6))

box = (825, 595, 1050, 705)
ox, oy = box[0], box[1]
L, rgb = S.load_gray(REF, box)
Lb = S.box_blur(L, 1)
yy, xx = np.mgrid[0:L.shape[0], 0:L.shape[1]]
U, V = xx + ox, yy + oy
roi = (U > 838) & (U < 1030) & (V > 610) & (V < 680)
DIV = (926.0, 934.0)                                  # the divider gap between the two dashes, u


def biggest(mask, n=1):
    loops = [lp for lp in S.boundary_loops(mask) if S.area(lp) > 0] or S.boundary_loops(mask)
    loops.sort(key=lambda lp: -abs(S.area(lp)))
    return loops[:n]


def shift(lp, sigma):
    p = S.smooth(lp, sigma, 0.5)
    p = S.resample(p, STEP)
    return [(round(float(a + ox), 2), round(float(b + oy), 2)) for a, b in p]


lens = S.closing(S.opening(Lb > 0.20, 1) & roi, 4) & roi
glass = biggest(lens)[0]
seg_o = biggest(lens & (U < DIV[0]))[0]
seg_i = biggest(lens & (U > DIV[1]))[0]
bars = S.opening(Lb > 0.62, 1) & roi
bar_o = biggest(bars & (U < DIV[0]))[0]
bar_i = biggest(bars & (U > DIV[1]))[0]
data = dict(
    DRL_GLASS=shift(glass, 2.4),
    DRL_SEG_O=shift(seg_o, 2.4), DRL_SEG_I=shift(seg_i, 2.4),
    DRL_BAR_O=shift(bar_o, 2.8), DRL_BAR_I=shift(bar_i, 2.8),
)
for k, v in data.items():
    print(k, len(v), "area %.0f" % abs(S.area(np.array(v))))

HAND = '''
# ---- the headlamp pod and the vent under it: hand readings of 7x crops (pixels of ext_front.jpg), clockwise on screen
# the pod's outer outline (the opening cut into the paint): a tall "D", straight at the outside, a big arc over the top
POD_OUT = [(849.5, 713.0), (851.0, 707.5), (855.0, 704.5), (865.0, 703.5), (877.0, 706.0), (888.0, 711.5), (897.0, 720.0),
           (904.0, 731.0), (908.5, 745.0), (910.0, 761.0), (909.5, 780.0), (909.0, 800.0), (907.5, 820.0), (903.5, 830.0),
           (880.0, 827.5), (856.0, 821.5), (849.0, 818.0)]
# the two lens units' bezels (silver rings, 1.5 px wide): the upper one has its outer top corner cut by a big radius
POD_BEZEL_U = [(861.0, 733.0), (880.0, 733.0), (889.0, 737.5), (893.5, 746.0), (893.5, 759.0), (890.5, 764.0),
               (863.0, 764.0), (859.0, 760.5), (858.0, 742.0)]
POD_BEZEL_L = [(862.0, 775.0), (886.0, 775.0), (891.0, 780.0), (891.0, 797.0), (886.0, 802.0), (862.0, 802.0),
               (857.0, 797.0), (857.0, 780.0)]
POD_LENS_U = (876.0, 748.5, 9.5)                       # the round projector lens (u, v, radius) inside the upper bezel
# the chrome sill under the lenses: a bright wedge, deep at the outside
POD_SILL = [(849.0, 809.0), (855.0, 807.5), (902.0, 826.0), (903.0, 830.0), (849.0, 821.5)]
VENT_OUT = [(849.0, 836.0), (870.0, 835.5), (906.0, 836.0), (907.0, 858.0), (906.0, 878.0), (901.0, 891.0), (885.0, 895.0),
            (860.0, 894.0), (851.0, 890.0), (847.0, 882.0), (848.0, 858.0)]
VENT_SLAB = [(882.0, 842.0), (898.0, 842.0), (899.0, 878.0), (894.0, 886.0), (882.0, 886.0)]
'''

with open(OUT, "w") as f:
    f.write('"""Nio ES8 headlamp, read off ext_front.jpg (2560 x 1280): generated by porting/es8_lamp_trace/gen_es8_lampdata.py.\n'
            'DRL_*: traced contours (pixels); POD_*, VENT_*: hand readings of 7x crops. The car\'s right half (picture left)."""\n')
    f.write("SIZE = (2560, 1280)\n")
    for k, v in data.items():
        f.write("%s = [\n" % k)
        row = []
        for p in v:
            row.append("(%.2f, %.2f)" % p)
            if len(row) == 6:
                f.write("    " + ", ".join(row) + ",\n")
                row = []
        if row:
            f.write("    " + ", ".join(row) + ",\n")
        f.write("]\n")
    f.write(HAND)
print("wrote", OUT)
